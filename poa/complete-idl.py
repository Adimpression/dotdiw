"""Complete the IDL that `poa derive` wrote, from the governed source.

derive rewrites operation-idl.json from scratch every time, from
poa/product-model.yaml, and writes of each operation what the model's
structure names: its duty, journey, step, objects, boundaries and timing.
What each operation takes, returns and calls, the kind, visibility and
idempotency it has, and the git and beads commands it runs are declared in
the model too, in the operation block of the step or journey it is derived
from; derive leaves them out, so this file writes them in. It reads nothing
but the governed source and the files POA keeps beside the IDL, so the
result is reproducible from them and never edited by hand:

  poa/product-model.yaml   each step's and journey's operation block; the
                           records the responses share; the git and beads
                           dependencies; the projections; and the change
                           records, the IDL's own wording of each under
                           idlRecord
  interface-bindings.cli.json
                           the command line's bindings, in place of the
                           `poa invoke` placeholders derive writes
  implementation-bindings.json
                           each operation bound to its body, and the number
                           of the tracker interface with the digest of its
                           types
  contracts/named-work-found-its-procedure.bindings.json
                           the witness contract and the observability, report
                           and summary bindings that answer to it
  this file                drops the placeholders, writes those in, rebuilds
                           what must agree with them, the operation call graph
                           and each implementation binding's calls, and writes
                           two tables into dotdiw between their markers: the
                           door's, for every operation a body answers, the
                           body's name and the fields of its request and
                           response; and the tracker door's, for every
                           operation of the tracker interface, the fields
                           alone, since an adapter answers those, with the
                           interface's number. This script refuses a change to
                           the types a module has to answer until someone has
                           decided whether to raise that number

The model is YAML, read through PyYAML from the locked dev group in one
function, so the rest of this file stays in the standard library and the
tests can load it.

    uv run python poa/complete-idl.py [operation-idl.json]
"""

import hashlib
import json
import os
import sys
import textwrap
from typing import Any

Idl = dict[str, Any]

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
IDL = os.path.join(ROOT, "operation-idl.json")
MODEL = os.path.join(HERE, "product-model.yaml")
CLI_BINDINGS = os.path.join(ROOT, "interface-bindings.cli.json")
IMPLEMENTATION = os.path.join(ROOT, "implementation-bindings.json")
CONTRACT_BINDINGS = os.path.join(ROOT, "contracts", "named-work-found-its-procedure.bindings.json")

GENERATED_BINDING = "binding.cli-invoke-"
BINDING_MODULE = "promise_bindings"

DOTDIW = os.path.join(ROOT, "dotdiw")
DOOR_OPEN = "# >>> generated from operation-idl.json by poa/complete-idl.py; do not edit\n"
DOOR_CLOSE = "# <<< end generated\n"
TRACKER_OPEN = (
    "# >>> tracker door generated from operation-idl.json by poa/complete-idl.py; do not edit\n"
)
TRACKER_CLOSE = "# <<< end tracker door\n"
TYPES_OPEN = "# >>> types generated from operation-idl.json by poa/complete-idl.py; do not edit\n"
TYPES_CLOSE = "# <<< end types\n"
SKELETON_OPEN = (
    "# >>> the file a tracker starts from, generated by poa/complete-idl.py; do not edit\n"
)
SKELETON_CLOSE = "# <<< end the file a tracker starts from\n"
# Fields an operation's docstring does not name, since an adapter's author has
# nothing to do with them: the door stamps tracker; the references and the
# correlation id are the IDL's own bookkeeping; and arguments, terminal and
# printed are for an adapter that runs a tracker's own command on the worker's
# terminal, which an adapter answering in records leaves alone.
SKELETON_LEAVES_OUT = (
    "tracker",
    "correlationId",
    "sourceRefs",
    "trackerRef",
    "trackerAdapterRef",
    "workRef",
    "moleculeRef",
    "formulaRefs",
    "resultRefs",
    "openQuestionRefs",
    "arguments",
    "terminal",
    "printed",
)
SCALARS = {"string": "str", "integer": "int", "boolean": "bool"}

# The operations of the tracker interface: the steps of this journey. An
# adapter answers them, so they have no body and sit in the inner table.
INNER_JOURNEY = "journey.answer-through-the-tracker"

# The id field of each list the governed source may extend.
ID_FIELDS = {
    "types": "typeId",
    "updates": "changeId",
    "eventStructureContracts": "contractId",
    "observabilityBindings": "bindingId",
    "reportBindings": "reportId",
    "storySummaryBindings": "summaryId",
    "interfaceBindings": "bindingId",
    "openQuestions": "questionId",
    "projections": "projectionId",
}


def load(path: str) -> Any:
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def by_id(items: list[dict[str, Any]], key: str) -> dict[str, dict[str, Any]]:
    return {item[key]: item for item in items}


def merge_list(idl: Idl, key: str, items: list[dict[str, Any]]) -> None:
    """Append, replacing an item that is already there under the same id."""
    field = ID_FIELDS[key]
    have = idl.setdefault(key, [])
    index = {item[field]: i for i, item in enumerate(have)}
    for item in items:
        if item[field] in index:
            have[index[item[field]]] = item
        else:
            index[item[field]] = len(have)
            have.append(item)


def call_kind(operation: dict[str, Any]) -> str:
    # The same rule derive uses, so a call it emitted and a call added here
    # get the same answer.
    sync = (operation.get("timing") or {}).get("syncExpectation")
    return "asynchronous" if sync == "asynchronous" else "synchronous"


def inner_operations(idl: Idl) -> list[dict[str, Any]]:
    """The tracker interface's operations, in the IDL's order."""
    return [
        op
        for op in idl["operations"]
        if any(d.get("sourceKind") == "gwt-step" for d in op.get("derivedFrom") or [])
        and (op.get("tracesTo") or {}).get("journeyIds") == [INNER_JOURNEY]
    ]


def implementation_bindings(idl: Idl, manifest: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Each binding implementation-bindings.json holds, with the operations its
    body calls: the operation's calls, as the model declares them."""
    calls = {
        op["operationId"]: [c["operationId"] for c in op.get("calls") or []]
        for op in idl["operations"]
    }
    out = []
    for binding in manifest:
        bound = {k: v for k, v in binding.items() if k != "notes"}
        bound["calledOperationIds"] = calls[binding["operationId"]]
        if "notes" in binding:
            bound["notes"] = binding["notes"]
        out.append(bound)
    return out


def load_model(path: str = MODEL) -> Any:
    """The governed source model, read through PyYAML."""
    import yaml

    with open(path, encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def operation_blocks(model: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """operation id -> the operation block of the step or journey it is derived from."""
    out = {}
    for kind, key in (("journeys", "journeyId"), ("steps", "stepId")):
        for entry in model.get(kind) or []:
            if "operation" in entry:
                out["operation." + entry[key].split(".", 1)[1]] = entry["operation"]
    return out


# The fields of a change record in the IDL, in the order the IDL writes them.
IDL_RECORD = (
    "changeId",
    "changeType",
    "targetRefs",
    "summary",
    "reason",
    "compatibility",
    "createdAt",
    "approvalStatus",
)


def idl_change_records(model: dict[str, Any]) -> list[dict[str, Any]]:
    """The model's change records that changed the IDL, in the IDL's words: its
    own record under idlRecord, or the record itself when it names the IDL."""
    out = []
    for update in model.get("updates") or []:
        if "idlRecord" in update:
            out.append({"changeId": update["changeId"], **update["idlRecord"]})
        elif "idl.dotdiw" in (update.get("targetRefs") or []):
            out.append({k: update[k] for k in IDL_RECORD if k in update})
    return out


def complete(
    idl: Idl,
    model: dict[str, Any],
    cli: dict[str, Any],
    manifest: dict[str, Any],
    contract: dict[str, Any],
) -> Idl:
    idl["interfaceBindings"] = [
        b
        for b in idl.get("interfaceBindings") or []
        if not b["bindingId"].startswith(GENERATED_BINDING)
    ]

    merge_list(idl, "updates", idl_change_records(model))
    for key in (
        "eventStructureContracts",
        "observabilityBindings",
        "reportBindings",
        "storySummaryBindings",
    ):
        merge_list(idl, key, contract[key])
    merge_list(idl, "types", model.get("operationTypes") or [])

    blocks = operation_blocks(model)
    ops = by_id(idl["operations"], "operationId")
    for op_id, block in blocks.items():
        op = ops[op_id]  # an unknown operation is an error, loudly
        for k, v in block.items():
            if k in ("requestFields", "responseFields"):
                continue
            if k == "derivedFrom":
                # Once each, so that running this twice gives the same file.
                have = op.setdefault("derivedFrom", [])
                have.extend(item for item in v if item not in have)
            elif k == "tracesTo":
                op["tracesTo"].update(v)
            else:
                op[k] = v

    types = by_id(idl["types"], "typeId")
    for op_id, block in blocks.items():
        for side, type_key in (
            ("requestFields", "requestType"),
            ("responseFields", "responseType"),
        ):
            if side not in block:
                continue
            fields = types[ops[op_id][type_key]].setdefault("fields", [])
            index = {f["name"]: i for i, f in enumerate(fields)}
            for f in block[side]:
                if f["name"] in index:
                    fields[index[f["name"]]] = f
                else:
                    index[f["name"]] = len(fields)
                    fields.append(f)

    idl["externalProductDependencies"] = model["externalProductDependencies"]
    merge_list(idl, "interfaceBindings", cli["bindings"])
    merge_list(idl, "projections", model.get("operationProjections") or [])

    # What has to agree with the calls above: poa check compares the two.
    idl["operationCallGraph"] = [
        {
            "fromOperationId": op["operationId"],
            "toOperationId": call["operationId"],
            "callKind": call_kind(op),
            "reason": call["callPurpose"],
        }
        for op in idl["operations"]
        for call in op.get("calls") or []
    ]
    idl["implementationBindings"] = implementation_bindings(idl, manifest["implementationBindings"])
    return idl


def names_tuple(key: str, names: list[str]) -> str:
    """One table entry: a tuple of field names, wrapped to the line."""
    if not names:
        return '        "%s": (),\n' % key
    text = ", ".join('"%s"' % n for n in names) + ","
    out = '        "%s": (\n' % key
    for line in textwrap.wrap(text, width=67, break_long_words=False, break_on_hyphens=False):
        out += "            %s\n" % line
    return out + "        ),\n"


def door_source(idl: Idl) -> str:
    """The door's table: what dotdiw holds between the markers.

    Sorted by operation id and field name, so that the same IDL always gives
    the same text and a test can regenerate it and compare.
    """
    types = by_id(idl["types"], "typeId")
    statuses: tuple[str, ...] = ()
    for op in idl["operations"]:
        status = [f for f in types[op["responseType"]]["fields"] if f["name"] == "status"]
        values = tuple(status[0]["valueType"]["values"])
        assert statuses in ((), values), "response types disagree on status"
        statuses = values
    # Only what a body answers: not the tracker interface, and not an
    # operation whose binding is not-yet-implemented, which the door refuses
    # as unknown until its phase lands it.
    inner = {op["operationId"] for op in inner_operations(idl)}
    pending = {
        b["operationId"]
        for b in idl.get("implementationBindings") or []
        if b["implementationMode"] == "not-yet-implemented"
    }
    out = DOOR_OPEN
    out += "STATUSES = (%s)\n\n" % ", ".join('"%s"' % s for s in statuses)
    out += "# operation id -> the body's name, the fields of its request, the required\n"
    out += "# ones among them, and the same for its response.\n"
    out += "DOOR: dict[str, DoorSpec] = {\n"
    for op in sorted(idl["operations"], key=lambda o: o["operationId"]):
        if op["operationId"] in inner or op["operationId"] in pending:
            continue
        req = types[op["requestType"]]["fields"]
        resp = types[op["responseType"]]["fields"]
        out += '    "%s": {\n' % op["operationId"]
        out += '        "body": "%s",\n' % op["name"]
        out += names_tuple("request", sorted(f["name"] for f in req))
        out += names_tuple("requestRequired", sorted(f["name"] for f in req if f["required"]))
        out += names_tuple("response", sorted(f["name"] for f in resp))
        out += names_tuple("responseRequired", sorted(f["name"] for f in resp if f["required"]))
        out += "    },\n"
    out += "}\n"
    return out + DOOR_CLOSE


def interface_digest(idl: Idl) -> str:
    """What a module written for the tracker interface relies on, as a short
    digest: each operation's fields, whether each is required, and the value
    types, following the shared records. The words describing them are left
    out, since a module cannot depend on those."""
    types = by_id(idl["types"], "typeId")

    def shape(value_type: dict[str, Any], seen: tuple[str, ...]) -> Any:
        kind = value_type["kind"]
        if kind == "type-ref":
            type_id = value_type["typeId"]
            return record(type_id, seen) if type_id not in seen else type_id
        if kind == "list":
            return ["list", shape(value_type["itemType"], seen)]
        if kind == "map":
            return ["map", shape(value_type["keyType"], seen), shape(value_type["valueType"], seen)]
        if kind == "enum-inline":
            return ["enum", sorted(value_type["values"])]
        return [kind, value_type.get("scalar")]

    def record(type_id: str, seen: tuple[str, ...]) -> Any:
        fields = sorted(types[type_id]["fields"], key=lambda f: f["name"])
        return [
            [f["name"], bool(f["required"]), shape(f["valueType"], seen + (type_id,))]
            for f in fields
        ]

    operations = [
        [op["operationId"], record(op["requestType"], ()), record(op["responseType"], ())]
        for op in sorted(inner_operations(idl), key=lambda o: o["operationId"])
    ]
    return hashlib.sha256(json.dumps(operations, sort_keys=True).encode()).hexdigest()[:16]


def interface_changed(idl: Idl, manifest: dict[str, Any]) -> str | None:
    """What to do when the interface no longer has the digest recorded for its
    number, or None when it has."""
    held = manifest["trackerInterface"]
    digest = interface_digest(idl)
    if digest == held["digest"]:
        return None
    return (
        "The tracker interface's types changed: digest %s, recorded %s for interface %d. "
        "If a module written for interface %d cannot answer the new types, raise the number "
        "in implementation-bindings.json. Either way, record the new digest there."
        % (digest, held["digest"], held["number"], held["number"])
    )


def tracker_door_source(idl: Idl) -> str:
    """The tracker door's table: the interface's number, then its operations
    and their fields, sorted like the door's. No body: an adapter answers
    each."""
    types = by_id(idl["types"], "typeId")
    out = TRACKER_OPEN
    out += "# The interface a module says it was written for. It is raised, by decision in\n"
    out += "# implementation-bindings.json, when a module written earlier cannot answer this one.\n"
    out += "TRACKER_INTERFACE = %d\n\n" % load(IMPLEMENTATION)["trackerInterface"]["number"]
    out += "# operation id -> the fields of its request, the required ones among them,\n"
    out += "# and the same for its response. The registered adapter answers.\n"
    out += "TRACKER_DOOR: dict[str, TrackerDoorSpec] = {\n"
    for op in sorted(inner_operations(idl), key=lambda o: o["operationId"]):
        req = types[op["requestType"]]["fields"]
        resp = types[op["responseType"]]["fields"]
        out += '    "%s": {\n' % op["operationId"]
        out += names_tuple("request", sorted(f["name"] for f in req))
        out += names_tuple("requestRequired", sorted(f["name"] for f in req if f["required"]))
        out += '        "requestType": %s,\n' % class_name(op["requestType"])
        out += names_tuple("response", sorted(f["name"] for f in resp))
        out += names_tuple("responseRequired", sorted(f["name"] for f in resp if f["required"]))
        out += '        "responseType": %s,\n' % class_name(op["responseType"])
        out += "    },\n"
    out += "}\n"
    return out + TRACKER_CLOSE


# What the file a tracker starts from holds besides its operations: the two
# functions that keep the means to prove a run as the last section of a root's
# description, for a tracker that has a description and nothing more for them.
# No backslash may appear in the file's text, so a newline is chr(10).
VERIFY_HELPER = '''

# A tracker with a title and a description and nothing more keeps the means to
# prove a run as the last section of an item's description, one to a line;
# these two write that section and read back exactly what they wrote. A
# tracker with a field of its own may keep them there instead: show-item gives
# back what pour-steps or create-item was given, however the tracker holds it.
NEWLINE = chr(10)
VERIFY_HEADING = "Verify using:"


def keep_verify_using(description: str | None, means: list[str]) -> str | None:
    """The description, with the means kept as its last section. With none,
    the description as given, or followed by an empty section when it would
    otherwise read back as holding one."""
    if means:
        block = NEWLINE.join([VERIFY_HEADING] + ["- " + m for m in means])
        return description + NEWLINE * 2 + block if description else block
    if not description or read_verify_using(description) == (description, []):
        return description
    return description + NEWLINE * 2 + VERIFY_HEADING


def read_verify_using(text: str | None) -> tuple[str | None, list[str]]:
    """The description as it was given, and the means kept in it: the last
    section headed Verify using:, at the start or after a blank line, whose
    lines to the end are each a means."""
    if not text:
        return text, []
    at = text.rfind(NEWLINE * 2 + VERIFY_HEADING)
    if at < 0 and not text.startswith(VERIFY_HEADING):
        return text, []
    start, description = (at + 2, text[:at]) if at >= 0 else (0, None)
    rest = text[start + len(VERIFY_HEADING) :]
    if not rest:
        return description, []
    lines = rest.split(NEWLINE)
    if lines[0] or not all(line.startswith("- ") and len(line) > 2 for line in lines[1:]):
        return text, []
    return description, [line[2:] for line in lines[1:]]
'''


def skeleton_source(idl: Idl) -> str:
    """What `dotdiw tracker new` writes, as text dotdiw holds between its own
    markers: the eleven operations raising until they are filled, each saying the
    fields it takes and answers, and the table that declares them. <NAME> is
    the tracker's name, put in when the file is written."""
    types = by_id(idl["types"], "typeId")
    operations = inner_operations(idl)

    def fields(type_id: str) -> str:
        return ", ".join(
            f["name"] + ("*" if f["required"] else "")
            for f in types[type_id]["fields"]
            if f["name"] not in SKELETON_LEAVES_OUT
        )

    def said(label: str, text: str) -> str:
        wrapped = textwrap.wrap(
            "%s: %s." % (label, text), width=74, break_long_words=False, break_on_hyphens=False
        )
        return "".join("    %s\n" % line for line in wrapped)

    body = '"""A tracker adapter for dotdiw: <NAME>.\n\n'
    body += "Run `dotdiw tracker check ./<NAME>.py`. It says which operations are left to\n"
    body += "answer, and the file is compatible when all %d pass. Each operation takes one\n" % (
        len(operations)
    )
    body += "dict and returns one. Read the fields its docstring names and answer with those\n"
    body += "alone; a star marks a required field. A module runs in dotdiw's own interpreter,\n"
    body += 'so it may import the standard library and nothing else.\n"""\n\n'
    body += "from typing import Any\n\nRecord = dict[str, Any]\n"
    body += VERIFY_HELPER
    for op in operations:
        slug = op["operationId"].split(".", 1)[1].replace("-", "_")
        reasons = [
            f["valueType"]["values"]
            for f in types[op["responseType"]]["fields"]
            if f["name"] == "reason"
        ]
        body += "\n\ndef %s(request: Record) -> Record:\n" % slug
        summary = " ".join(op["summary"].split()).replace(": ", ". ", 1)
        lines = textwrap.wrap(summary, width=74, break_long_words=False, break_on_hyphens=False)
        body += '    """%s\n' % lines[0]
        body += "".join("    %s\n" % line for line in lines[1:])
        body += "\n"
        body += said("Takes", fields(op["requestType"]))
        body += said("Answers", fields(op["responseType"]))
        if reasons:
            body += said("Reasons", ", ".join(reasons[0]))
        body += '    """\n'
        body += '    raise NotImplementedError("%s")\n' % slug
    body += "\n\nTRACKER = {\n"
    body += '    "info": {\n'
    body += '        "name": "<NAME>",\n'
    body += '        "version": "0.1.0",\n'
    body += '        "interface": %d,\n' % load(IMPLEMENTATION)["trackerInterface"]["number"]
    body += '        "nativeNeeds": True,\n'
    body += '        "checkTarget": "scratch",\n'
    body += '        "extras": [],\n'
    body += "    },\n"
    body += '    "operations": {\n'
    for op in operations:
        slug = op["operationId"].split(".", 1)[1].replace("-", "_")
        body += '        "%s": %s,\n' % (op["operationId"], slug)
    body += "    },\n"
    body += '    "extras": {},\n'
    body += "}\n"
    assert "'''" not in body and "\\" not in body
    return SKELETON_OPEN + "TRACKER_SKELETON = '''" + body + "'''\n" + SKELETON_CLOSE


def class_name(type_id: str) -> str:
    """type.list-items-response -> ListItemsResponse."""
    return "".join(word.capitalize() for word in type_id.split(".", 1)[1].split("-"))


def literal_source(values: list[str], indent: str, room: int = 90) -> str:
    """Literal[...] over the values, wrapped to the line when they do not fit
    in the room the field's line leaves for them."""
    flat = "Literal[%s]" % ", ".join('"%s"' % v for v in values)
    if len(flat) <= room:
        return flat
    out = "Literal[\n"
    text = ", ".join('"%s"' % v for v in values) + ","
    for line in textwrap.wrap(
        text, width=88 - len(indent), break_long_words=False, break_on_hyphens=False
    ):
        out += "%s    %s\n" % (indent, line)
    return out + indent + "]"


def annotation_source(
    value_type: dict[str, Any], statuses: tuple[str, ...], indent: str, room: int = 90
) -> str:
    """The Python annotation for one IDL value type, given the room its line
    leaves for it."""
    kind = value_type["kind"]
    if kind == "scalar":
        return SCALARS[value_type["scalar"]]
    if kind == "enum-inline":
        values = list(value_type["values"])
        return "Status" if tuple(values) == statuses else literal_source(values, indent, room)
    if kind == "reference":
        return "str"  # an id of the object it names
    if kind == "type-ref":
        return class_name(value_type["typeId"])
    if kind == "list":
        return "list[%s]" % annotation_source(value_type["itemType"], statuses, indent, room - 6)
    if kind == "map":
        return "dict[%s, %s]" % (
            annotation_source(value_type["keyType"], statuses, indent),
            annotation_source(value_type["valueType"], statuses, indent),
        )
    raise ValueError("no annotation for a value of kind %s" % kind)


def types_source(idl: Idl) -> str:
    """The IDL's record types as TypedDicts: what dotdiw holds between the
    types markers. The shared records first, then each operation's request
    and response, in the IDL's order, so that the same IDL always gives the
    same text and a test can regenerate it and compare."""
    types = by_id(idl["types"], "typeId")
    statuses: tuple[str, ...] = ()
    for op in idl["operations"]:
        status = [f for f in types[op["responseType"]]["fields"] if f["name"] == "status"]
        statuses = tuple(status[0]["valueType"]["values"])
    records = [t for t in idl["types"] if t["kind"] == "record"]
    shared = [t for t in records if not t["typeId"].endswith(("-request", "-response"))]
    owned = [t for t in records if t["typeId"].endswith(("-request", "-response"))]
    out = TYPES_OPEN
    out += "# One class per record type of the IDL, the shared records first. A field the\n"
    out += "# IDL requires is Required; the rest may be absent or None, which the doors\n"
    out += "# read alike. An error type is the transport's, not a record a body answers\n"
    out += "# with, and has no class here.\n"
    out += "Status = %s\n" % literal_source(list(statuses), "")
    for t in shared + owned:
        out += "\n\nclass %s(TypedDict, total=False):\n" % class_name(t["typeId"])
        summary = " ".join((t.get("description") or t["name"]).split())
        lines = textwrap.wrap(summary, width=92, break_long_words=False, break_on_hyphens=False)
        if len(lines) == 1:
            out += '    """%s"""\n' % lines[0]
        else:
            out += '    """%s\n' % lines[0]
            for line in lines[1:]:
                out += "    %s\n" % line
            out += '    """\n'
        for f in t["fields"]:
            wrap = "Required[%s]" if f["required"] else "%s | None"
            room = 100 - len("    %s: " % f["name"]) - len(wrap % "")
            inner = annotation_source(f["valueType"], statuses, "    ", room)
            field = wrap % inner
            out += "    %s: %s\n" % (f["name"], field)
    return out + TYPES_CLOSE


def replace_region(text: str, open_marker: str, close_marker: str, body: str, path: str) -> str:
    assert text.count(open_marker) == 1 and text.count(close_marker) == 1, (
        "%s must hold the markers %r exactly once" % (path, open_marker.strip())
    )
    head, rest = text.split(open_marker, 1)
    tail = rest.split(close_marker, 1)[1]
    return head + body + tail


def write_door(idl: Idl, path: str = DOTDIW) -> bool:
    """Put both tables, the types and the starting file between their markers in
    dotdiw; True when that changed it."""
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    after = replace_region(text, DOOR_OPEN, DOOR_CLOSE, door_source(idl), path)
    after = replace_region(after, TRACKER_OPEN, TRACKER_CLOSE, tracker_door_source(idl), path)
    after = replace_region(after, TYPES_OPEN, TYPES_CLOSE, types_source(idl), path)
    after = replace_region(after, SKELETON_OPEN, SKELETON_CLOSE, skeleton_source(idl), path)
    if after == text:
        return False
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(after)
    return True


def main(argv: list[str]) -> int:
    path = argv[1] if len(argv) > 1 else IDL
    manifest = load(IMPLEMENTATION)
    idl = complete(load(path), load_model(), load(CLI_BINDINGS), manifest, load(CONTRACT_BINDINGS))
    changed_interface = interface_changed(idl, manifest)
    if changed_interface:
        print(changed_interface, file=sys.stderr)
        return 1
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(idl, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    print(
        "completed %s: %d operations, %d interface bindings, %d call edges"
        % (
            os.path.relpath(path, ROOT),
            len(idl["operations"]),
            len(idl["interfaceBindings"]),
            len(idl["operationCallGraph"]),
        )
    )
    changed = write_door(idl)
    inner = {op["operationId"] for op in inner_operations(idl)}
    pending = {
        b["operationId"]
        for b in idl["implementationBindings"]
        if b["implementationMode"] == "not-yet-implemented"
    }
    print(
        "the doors in %s: %d operations with a body, %d of the tracker, %d not yet, "
        "%d record types, %s"
        % (
            os.path.relpath(DOTDIW, ROOT),
            len(idl["operations"]) - len(inner | pending),
            len(inner),
            len(pending - inner),
            sum(1 for t in idl["types"] if t["kind"] == "record"),
            "rewritten" if changed else "unchanged",
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
